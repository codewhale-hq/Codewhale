// Third-party notices (`dist/LICENSES.txt`), generated from what the bundler
// actually put in the host bundle: every package that contributed an input
// file, with its own LICENSE file. A package added to or dropped from the
// bundle changes this file, and CI's `git diff --exit-code -- dist` then
// catches a stale one. The Rust core embeds this file and writes it beside the
// materialised bundle, so the banner's promise ("LICENSES.txt next to this
// file") holds for every installed copy.
const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md', 'COPYING']

function bundledPackages(metafile) {
  const found = new Map()
  for (const input of Object.keys(metafile.inputs)) {
    const marker = 'node_modules/'
    const at = input.lastIndexOf(marker)
    if (at < 0) continue
    const [first, second] = input.slice(at + marker.length).split('/')
    const name = first.startsWith('@') ? `${first}/${second}` : first
    found.set(name, join(here, input.slice(0, at + marker.length), name))
  }
  return [...found.entries()].sort(([a], [b]) => (a < b ? -1 : 1)).map(([name, root]) => ({ name, root }))
}

function readLicense(root, label) {
  for (const file of LICENSE_FILES) {
    try {
      return readFileSync(join(root, file), 'utf8').trim()
    } catch {}
  }
  throw new Error(`${label} is bundled but ships no LICENSE file in ${root}; add its notice by hand before releasing`)
}

// Source vendored into `src/` verbatim rather than imported from node_modules.
// The metafile cannot see these, so each names the file that carries the
// excerpt and the bundled package whose licence text it shares (checked below).
const EXCERPTED = [
  {
    name: '@deepseek-ai/dsh-tools',
    version: compatibility.definition_api.version,
    license: 'MIT',
    file: 'src/dsh/dsh-tools-compat.js',
    licenseOf: '@deepseek-ai/dsh-util-values',
  },
  ...compatibility.pure_api.packages.filter(pkg => pkg.excerpted).map(pkg => ({
    name: pkg.package,
    version: pkg.version,
    license: pkg.license,
    file: compatibility.pure_api.file,
    sourceSha256: compatibility.pure_api.source_sha256,
    licenseTextSha256: pkg.license_text_sha256,
    licenseOf: '@deepseek-ai/dsh-util-values',
  })),
]

const packageInputs = [hostBuild.metafile, reviewBuild.metafile, ...builtinMetafiles].flatMap(bundledPackages)
const packagesByIdentity = new Map()
for (const { name, root } of packageInputs) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  if (typeof pkg.license !== 'string' || pkg.license.length === 0) throw new Error(`${name} declares no license in package.json`)
  const entry = { name: pkg.name, version: pkg.version, license: pkg.license, text: readLicense(root, name) }
  const identity = `${entry.name}@${entry.version}`
  const prior = packagesByIdentity.get(identity)
  if (prior && (prior.license !== entry.license || prior.text !== entry.text)) throw new Error(`${identity} contributes conflicting licence texts`)
  packagesByIdentity.set(identity, entry)
}
const packages = [...packagesByIdentity.values()]
if (packages.length === 0) throw new Error('the host bundle contains no node_modules input: the notice generator is reading the wrong metafile')

const entries = packages.map((pkg) => ({ ...pkg, note: '' }))
for (const excerpt of EXCERPTED) {
  const source = readFileSync(join(here, excerpt.file), 'utf8')
  if (excerpt.sourceSha256 ? createHash('sha256').update(source).digest('hex') !== excerpt.sourceSha256 : !source.includes(`${excerpt.name}@${excerpt.version}`)) {
    throw new Error(`${excerpt.file} no longer names ${excerpt.name}@${excerpt.version}; update EXCERPTED in build.mjs`)
  }
  const shared = packages.find((pkg) => pkg.name === excerpt.licenseOf)
  if (!shared) throw new Error(`${excerpt.licenseOf} (licence text of ${excerpt.name}) is not bundled`)
  if (excerpt.licenseTextSha256 && (shared.license !== excerpt.license || createHash('sha256').update(shared.text).digest('hex') !== excerpt.licenseTextSha256)) {
    throw new Error(`${excerpt.name} licence text differs from its pinned pure helper receipt`)
  }
  entries.push({
    name: excerpt.name,
    version: excerpt.version,
    license: excerpt.license,
    text: shared.text,
    note: `Verbatim excerpts of this package are in ${excerpt.file}, under the same licence text as ${excerpt.licenseOf} above.`,
  })
}
for (const [folder, version] of [['loader', '1.0.3'], ['include', '1.0.7'], ['group', '1.0.2']]) {
  entries.push({
    name: `@deepseek-ai/cordis-plugin-${folder}`,
    version,
    license: 'MIT',
    text: readLicense(join(here, 'src/dsh/upstream', folder), `vendored ${folder}`),
    note: 'Pinned deepseek-harness 0d1f50007f9bca3f52b06e1c3074fa14d5fb0720. Loader native-internals probe disabled; other runtime semantics reused.',
  })
}
entries.push({name:'@deepseek-ai/dsh-agent-presets',version:'0.1.6-alpha.1',license:'MIT',text:readLicense(join(here,'src/dsh/upstream/agent-presets'),'vendored agent-presets'),note:'Pinned deepseek-harness 0d1f50007f9bca3f52b06e1c3074fa14d5fb0720. Discovery/metadata/specifier/inventory algorithms use mandatory receipt-backed IO; Core owns selection, sessions and writable roots.'})
for (const name of ['dsh-hook-protocol', 'dsh-hooks-claude-code', 'dsh-hooks-codex']) {
  entries.push({
    name: `@deepseek-ai/${name}`,
    version: '0.1.6-alpha.1',
    license: 'MIT',
    text: readLicense(join(here, 'src/dsh/upstream/hooks'), `vendored ${name}`),
    note: 'Pinned deepseek-harness 0d1f50007f9bca3f52b06e1c3074fa14d5fb0720. Pure matcher/codec/merge and configuration parsers reused; local imports and session-writer type declarations adapted. Core retains scheduling and steering.',
  })
}
for (const name of ['dsh-persona', 'dsh-system-prompt']) {
  entries.push({
    name: `@deepseek-ai/${name}`,
    version: '0.1.6-alpha.1',
    license: 'MIT',
    text: readLicense(join(here, 'src/dsh/upstream/hooks'), `adapted ${name}`),
    note: 'Pinned deepseek-harness 0d1f50007f9bca3f52b06e1c3074fa14d5fb0720. Additive persona configuration and strict simple template mapping adapted in src/dsh/persona.ts and the Rust prompt renderer; source and license receipts: src/dsh/persona.UPSTREAM.json. Core retains prompt assembly and accepted model/workspace values.',
  })
}
entries.sort((a, b) => (a.name < b.name ? -1 : 1))

const sections = [
  'Third-party software bundled into codewhale-extension-host.mjs, dsh-composition-review.mjs and builtin/*.mjs.',
  'Generated by crates/engine/extension-host/build.mjs from the bundler metafile; do not edit.',
  '',
  'Packages:',
  ...entries.map((entry) => `  ${entry.name}@${entry.version} (${entry.license})`),
]
for (const entry of entries) {
  sections.push('', '='.repeat(72), `${entry.name}@${entry.version} (${entry.license})`, '='.repeat(72))
  if (entry.note) sections.push('', entry.note)
  sections.push('', entry.text)
}
// Preserve every notice word while keeping generated text free of trailing whitespace.
writeFileSync(join(outdir, 'LICENSES.txt'), sections.join('\n').replace(/[ \t]+$/gm, '') + '\n')
