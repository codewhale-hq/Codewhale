#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(
  process.argv[2] ??
    process.env.CODEWHALE_MARKETPLACE ??
    [resolve(here, "../../../codewhale-plugin-marketplace"), resolve(here, "../../../../codewhale-plugin-marketplace")].find((p) =>
      existsSync(resolve(p, "marketplace.json")),
    ) ??
    "codewhale-plugin-marketplace",
);

const marketplace = JSON.parse(readFileSync(resolve(root, "marketplace.json"), "utf8"));
const catalog = JSON.parse(readFileSync(resolve(root, "connections/catalog.json"), "utf8"));

const AUTH = { oauth: "oauth", bearer: "token", none: "none" };
const connectors = catalog.connections
  .filter((c) => c.status === "documented")
  .map((c) => {
    const auth = AUTH[c.auth];
    if (!auth) throw new Error(`connector ${c.id}: unknown auth ${c.auth}`);
    return { id: c.id, name: c.name, url: c.url, auth };
  });

const plugins = marketplace.plugins.map((p) => ({ name: p.name, version: p.version }));

const out = `// Generated by scripts/derive-connectors.mjs from codewhale-plugin-marketplace
// (connections/catalog.json checked ${catalog.checked_at}). Do not edit by hand.
export type ConnectorAuth = "oauth" | "token" | "none";

export const CONNECTORS: readonly { id: string; name: string; url: string; auth: ConnectorAuth }[] = ${JSON.stringify(connectors, null, 2)};

export const CATALOG_PLUGINS: readonly { name: string; version: string }[] = ${JSON.stringify(plugins, null, 2)};
`;
writeFileSync(resolve(here, "../lib/content/connectors.generated.ts"), out);
console.log(`[derive-connectors] wrote ${connectors.length} connectors and ${plugins.length} plugins from ${root}`);
